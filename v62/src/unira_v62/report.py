"""Generate outputs/REPORT_TABLES.md from outputs/*.csv|json (no hand-typed numbers)."""
import csv
import json
from pathlib import Path

NAMES = {"A": "Agriculture", "B": "Mining", "C": "Manufacturing", "D": "Electricity/gas",
         "E": "Water/waste", "F": "Construction", "G": "Trade", "H": "Transport/storage",
         "I": "Accommodation/food", "J": "Info/comm", "K": "Finance", "L": "Real estate",
         "M": "Professional/scientific", "N": "Admin/support", "O": "Public admin",
         "P": "Education", "Q": "Health/social work", "R": "Arts/recreation",
         "S": "Other services", "T": "Households as employers", "TOTAL_bottom_up": "TOTAL"}


def f(v, scale=1.0, nd=1, pct=False):
    if v in ("", None):
        return "n/a"
    if v == "inf":
        return "never (trend <= 0)"
    x = float(v) * (100 if pct else scale)
    return f"{x:,.{nd}f}"


def build(out_dir, cfg):
    out_dir = Path(out_dir)
    rows = list(csv.DictReader((out_dir / "labour_sector_year.csv").open()))
    summary = json.loads((out_dir / "summary.json").read_text())
    y = cfg["base_year"]
    L = [f"# UNIRA V6.2 — generated result tables (base year {y})", "",
         "Generated by `run_all.py` from `outputs/labour_sector_year.csv` and `outputs/summary.json`. "
         "Do not edit by hand.", "", "## 1. Scenario totals (France, all NACE sections A–T)", "",
         "| year | scenario | hours before (bn) | hours after (bn) | required hourly productivity gain | "
         "extra persons, same profile (m) | years of 2015–19 VA/hour trend | years of 2015–23 VA/hour trend |", "|---|---|---|---|---|---|---|---|"]
    for key, s in summary["scenarios"].items():
        yr, sid = key.split(":")
        L.append(f"| {yr} | {sid} | {f(s['hours_before_ths'], 1e-6, 2)} | {f(s['hours_after_ths'], 1e-6, 2)} | "
                 f"{f(s['required_hourly_productivity_gain'], pct=True)}% | "
                 f"{f(s['additional_persons_same_profile_ths'], 1e-3, 2)} | "
                 f"{f(s['years_of_trend_2015_2019_to_cover_gain'], nd=0)} | "
                 f"{f(s['years_of_trend_2015_2023_to_cover_gain'], nd=0)} |")
    for sid in (cfg["primary_scenario"], cfg["upper_scenario"]):
        L += ["", f"## 2. Sector detail — `{sid}`, {y}", "",
              "| NACE | sector | hours/person observed | part-time share (employees) | hours lost | "
              "required gain | extra persons (k) | VA/hour trend 2015–19 | years to cover | VA/hour trend 2015–23 | years to cover | caveat |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            if r["year"] == str(y) and r["scenario"] == sid:
                lost = 1 - float(r["hours_retention_ratio"])
                L.append(f"| {r['nace_r2']} | {NAMES.get(r['nace_r2'], '')} | {f(r['hours_per_person_before'], nd=0)} | "
                         f"{f(r.get('SAL_part_time_share'), pct=True)}{'%' if r.get('SAL_part_time_share') else ''} | {lost*100:.1f}% | "
                         f"{f(r['required_hourly_productivity_gain'], pct=True)}% | "
                         f"{f(r['additional_persons_same_profile_ths'], nd=0)} | "
                         f"{f(r['trend_va_per_hour_2015_2019'], pct=True, nd=2)}% | "
                         f"{f(r['years_of_trend_2015_2019_to_cover_gain'], nd=0)} | "
                         f"{f(r['trend_va_per_hour_2015_2023'], pct=True, nd=2)}% | "
                         f"{f(r['years_of_trend_2015_2023_to_cover_gain'], nd=0)} | {r['output_measure_caveat']} |")
    L += ["", f"## 2b. Residual required gain if a share θ of lost hours is offset by higher hourly productivity ({y})", "",
          "θ is a sensitivity grid, not an estimate; see audit/hours_productivity_evidence.md.", "",
          "| scenario | " + " | ".join(f"θ={th}" for th in cfg["offset_grid_theta"]) + " |",
          "|---|" + "---|" * len(cfg["offset_grid_theta"])]
    for sid, grid in summary["offset_grid"].items():
        L.append(f"| {sid} | " + " | ".join(f"{grid[str(th)]*100:.1f}%" for th in cfg["offset_grid_theta"]) + " |")
    L += ["", f"## 3. Labour-market slack (LFS, thousand persons, 15–74)", "",
          "| year | unemployed | underemployed part-time | seeking not available | available not seeking | total slack |",
          "|---|---|---|---|---|---|"]
    for yr, s in summary["slack_ths"].items():
        L.append(f"| {yr} | {s['UNE']} | {s['UEMP_PT']} | {s['SEEK_NAVL']} | {s['NSEEK_AVL']} | {s['SLACK']} |")
    L += ["", "## 4. Rounding bounds on required gain (LFS means ±0.05 h)", ""]
    for k, (lo, hi) in summary["rounding_bounds_required_gain"].items():
        L.append(f"- {k}: {lo*100:.2f}% – {hi*100:.2f}%")
    L += ["", "## 5. NA × LFS reconciliation with INSEE LFS annual hours", "",
          "| year | NA hours/employee | implied FT employee h/yr | implied PT employee h/yr | NA hours/self-employed | implied effective weeks |",
          "|---|---|---|---|---|---|"]
    for r in summary["insee_reconciliation"]:
        L.append(f"| {r['year']} | {f(r['na_hours_per_employee'], nd=0)} | {f(r['implied_ft_employee_annual_hours'], nd=0)} | "
                 f"{f(r['implied_pt_employee_annual_hours'], nd=0)} | {f(r['na_hours_per_self_employed'], nd=0)} | "
                 f"{f(r['implied_employee_effective_weeks'], nd=1)} |")
    last = summary["insee_reconciliation"][-1]
    if "insee_ft_employee_annual_hours" in last:
        L.append(f"\nINSEE 2025 LFS: FT employees {last['insee_ft_employee_annual_hours']} h, PT employees "
                 f"{last['insee_pt_employee_annual_hours']} h, self-employed {last['insee_self_employed_annual_hours']} h. "
                 f"Ratios implied/INSEE: FT {last['ratio_implied_to_insee_ft']:.3f}, PT {last['ratio_implied_to_insee_pt']:.3f}, "
                 f"self-employed (NA/INSEE) {last['ratio_na_to_insee_self_employed']:.3f}.")
    L += reserve_section(out_dir, cfg)
    L += ["", f"## 8. Evidence-graded pathway, France, employees capped ({y}): 30 h vs 35 h", "",
          "θ by sector from audit/hours_productivity_evidence.md (care = P, Q); mobilisation = benchmark framing × take-up "
          "(SYNTHETIC) × entrant productivity (SYNTHETIC). Entrants work the capped week.", "",
          "| weekly cap | case | θ market / care | take-up | entrant productivity | gain needed, no offsets | share closed by θ | share closed by mobilisation | residual required gain | years of 2015–19 trend |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for cap, cases in summary["evidence_pathway_FR"].items():
        spec = cfg["evidence_pathway"]["by_cap"][cap]
        g0 = summary["scenarios"][f"{y}:{spec['scenario']}"]["required_hourly_productivity_gain"]
        for name, r in cases.items():
            c = spec["cases"][name]
            L.append(f"| {cap} h | {name} | {c['theta_market']} / {c['theta_care']} | {c['take_up']} | "
                     f"{c['entrant_relative_productivity']} | {g0*100:.1f}% | {r['share_closed_by_theta']*100:.0f}% | "
                     f"{r['share_closed_by_mobilisation']*100:.0f}% | {r['residual_required_gain']*100:.1f}% | "
                     f"{f(r['years_of_2015_2019_trend'], nd=0)} |")
    L += ["", f"## 6. Checks: {summary['checks_passed']}/{summary['checks_total']} passed; failed: "
          f"{summary['checks_failed'] or 'none'} (see outputs/checks.csv; INFO rows are diagnostics)", ""]
    (out_dir / "REPORT_TABLES.md").write_text("\n".join(L))


def _pearson(xs, ys):
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    cov = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    vx = sum((x - mx) ** 2 for x in xs) ** 0.5
    vy = sum((y - my) ** 2 for y in ys) ** 0.5
    return cov / (vx * vy)


def reserve_section(out_dir, cfg):
    path = Path(out_dir) / "labour_reserve_country_year.csv"
    rows = [r for r in csv.DictReader(path.open()) if r["year"] == str(cfg["base_year"])
            and r["weekly_cap"] == "30"]
    get = lambda geo, ap, rho: next((r for r in rows if r["geo"] == geo and r["apply_to"] == ap
                                     and float(r["entrant_relative_productivity"]) == rho), None)
    L = ["", f"## 7. Labour reserve: can people not working today fill the 30 h gap? ({cfg['base_year']}, ages 20–64)", "",
         "Upper bounds: full take-up, perfect skill/location matching. Entrants work 30 h/week. "
         "Framings are alternatives (benchmark already contains the unemployed). "
         "Benchmark = mean of the three highest 20–64 employment rates among EU27+IS/NO/CH.", "",
         "| country | employment rate 20–64 | 55–64 | usual h/week (all) | gap: required gain, no mobilisation | "
         "unemployed (k) | extended LF (k) | underemployed PT (k) | share of gap closed: slack | : benchmark | "
         "residual gain, benchmark | residual, benchmark, entrants at 75% productivity | flag |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    geos = sorted({r["geo"] for r in rows}, key=lambda g: (g == "EU27_2020", g))
    for g in geos:
        a, b = get(g, "SAL", 1.0), get(g, "SAL", 0.75)
        if not a:
            continue
        L.append(f"| {g} | {f(a['employment_rate'])}% | {f(a['employment_rate_55_64'])}% | {f(a['lfs_usual_hours_all'])} | "
                 f"{f(a['required_gain_no_mobilisation'], pct=True)}% | {f(a['t1_unemployed_ths'], nd=0)} | "
                 f"{f(a['t2_extended_lf_ths'], nd=0)} | {f(a['t3_underemployed_pt_ths'], nd=0)} | "
                 f"{f(a['slack_gap_closed_share'], pct=True, nd=0)}% | {f(a['bench_top3_gap_closed_share'], pct=True, nd=0)}% | "
                 f"{f(a['bench_top3_residual_gain'], pct=True)}% | {f(b['bench_top3_residual_gain'], pct=True)}% | {a['weeks_flag']} |")
    a = get("FR", "SAL", 1.0)
    L.append(f"\nBenchmark employment rate: {float(a['bench_top3_rate']):.1f}% ({a['bench_top3_countries']}). "
             "Cap applied to employees only (primary); `outputs/labour_reserve_country_year.csv` also has the all-workers variant.")
    pts = [(float(r["lfs_usual_hours_all"]), float(r["employment_rate"])) for r in rows
           if r["apply_to"] == "SAL" and float(r["entrant_relative_productivity"]) == 1.0
           and r["geo"] != "EU27_2020" and r["lfs_usual_hours_all"]]
    L.append(f"\nDescriptive cross-country correlation (n={len(pts)}) between average usual weekly hours and the 20–64 "
             f"employment rate: r = {_pearson(*zip(*pts)):.2f}. Correlation only: part-time prevalence, demography, "
             "institutions and GDP per capita confound it; it is not evidence that shorter hours cause higher employment.")
    return L
