"""UNIRA V6.3 year-1 feasibility ledger for a 30 h week from the start.

All quantities in thousand hours per year (physical labour time), never euros.
Sources (all regenerated by their own pipelines, read here):
  gap, sectors, reserve pools  ../../v62/outputs/{labour_sector_year,labour_reserve_country_year}.csv
  theta ranges                 ../../v62/config/v62_config.json (evidence_pathway, from literature review)
  take-up rates                ../flows/outputs/takeup_rates.csv
  avoidable output             ../io/outputs/summary.json   (France 2022 shares)
  health staffing              ../health/outputs/health_staffing.csv

Regions: FR (regional pilot) and EU27_2020 treated as ONE pooled entity (UNIRA:
countries are regions of one world; labour is pooled by locating production where
people are available, not by forced relocation). The France avoidable-output share
is applied to EU27 as a proxy (flagged).

Mobilisation (net additions in year 1) is NOT the observed gross job-finding rate,
which mostly reflects churn offset by job losses. Variants:
  best_practice_gap  take-up = top-3 observed rate - own rate   (empirical central)
  best_practice_full take-up = top-3 observed rate              (optimistic)
  job_guarantee      take-up = 100% of slack pools              (theoretical upper)
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
UNIRA = ROOT.parents[1]

CASES = {  # theta, mobilisation variant, avoidable level, entrant productivity
    "low": {"theta": "low", "mobilisation": "best_practice_gap", "avoidable": "modest", "rho": 0.75},
    "central": {"theta": "central", "mobilisation": "best_practice_gap", "avoidable": "moderate", "rho": 0.75},
    "optimistic": {"theta": "high", "mobilisation": "best_practice_full", "avoidable": "deep", "rho": 1.0},
    "maximal": {"theta": "high", "mobilisation": "job_guarantee", "avoidable": "deep", "rho": 1.0},
    # Rule 14 (user, 2026-11-03): everyone able to work, works. Employment rate 20-64
    # raised to a target; entrants at 75% productivity in year 1; central theta and avoidable output.
    "universal_84": {"theta": "central", "mobilisation": "universal:84", "avoidable": "moderate", "rho": 0.75},
    "universal_88": {"theta": "central", "mobilisation": "universal:88", "avoidable": "moderate", "rho": 0.75},
    "universal_92": {"theta": "central", "mobilisation": "universal:92", "avoidable": "moderate", "rho": 0.75},
}


def read_csv(p):
    with Path(p).open() as f:
        return list(csv.DictReader(f))


def takeup(rows, geo, pool, role):
    for r in rows:
        if r["geo"] == geo and r["year"] == "2023" and r["pool"] == pool and r["role"] == role \
                and r["takeup_rate"] not in ("", "MISSING"):
            return float(r["takeup_rate"])
    return None


def mobilisation_rates(rows, geo, variant):
    own1, own2 = takeup(rows, geo, "T1", "proposed"), takeup(rows, geo, "T2", "proposed")
    top1 = next(float(r["takeup_rate"]) for r in rows if r["geo"] == "TOP3_MEAN" and r["pool"] == "T1"
                and r["year"] == "2023" and r["role"] == "benchmark")
    top2 = max(float(r["takeup_rate"]) for r in rows if r["geo"] == "TOP3_MEAN" and r["pool"] == "T2"
               and r["year"] == "2023" and r["role"] == "benchmark")
    if variant == "best_practice_gap":
        return max(0.0, top1 - own1), max(0.0, top2 - own2), 0.0
    if variant == "best_practice_full":
        return top1, top2, takeup(rows, geo, "T3", "proposed") or 0.0
    if variant == "job_guarantee":
        return 1.0, 1.0, 1.0
    raise ValueError(variant)


def gap_and_theta(sector_rows, theta, care):
    H0 = sum(float(r["hours_before_ths"]) for r in sector_rows)
    H1 = sum(float(r["hours_after_ths"]) for r in sector_rows)
    off = sum((theta["theta_care"] if r["nace_r2"] in care else theta["theta_market"])
              * (float(r["hours_before_ths"]) - float(r["hours_after_ths"])) for r in sector_rows)
    return H0, H1, off


def ledger(region, case_name, case, inputs):
    v62cfg, sectors, reserve, flows, io = (inputs[k] for k in ("v62cfg", "sectors", "reserve", "flows", "io"))
    ep = v62cfg["evidence_pathway"]
    theta = ep["by_cap"]["30"]["cases"][case["theta"]]
    res = next(r for r in reserve if r["geo"] == region and r["year"] == "2023" and r["weekly_cap"] == "30"
               and r["apply_to"] == "SAL" and float(r["entrant_relative_productivity"]) == 1.0)
    if region == "FR":
        H0, H1, off = gap_and_theta(sectors, theta, ep["care_sectors"])
    else:  # EU27: top-down gap; theta applied with France's sector mix of lost hours (proxy)
        H0, H1 = float(res["hours_before_ths"]), float(res["hours_after_ths"])
        fH0, fH1, foff = gap_and_theta(sectors, theta, ep["care_sectors"])
        off = (H0 - H1) * foff / (fH0 - fH1)
    entrant_h = float(res["entrant_annual_hours"])
    if case["mobilisation"].startswith("universal:"):
        target = float(case["mobilisation"].split(":")[1])
        persons = max(0.0, (target - float(res["employment_rate"])) / 100 * float(res["population_ths"]))
        r1 = r2 = r3 = 1.0
        mob = (persons * entrant_h + float(res["t3_extra_hours_ths"])) * case["rho"]
    else:
        r1, r2, r3 = mobilisation_rates(flows, region, case["mobilisation"])
        persons = float(res["t1_unemployed_ths"]) * r1 + float(res["t2_extended_lf_ths"]) * r2
        mob = (persons * entrant_h + float(res["t3_extra_hours_ths"]) * r3) * case["rho"]
    a_share = io["2022"]["market_candidates"][case["avoidable"]]["share_of_total_hours"]
    avoid = a_share * H0
    gap = H0 - H1
    covered = min(gap, off + mob + avoid)
    # output still required = H0*(1-a) hour-equivalents; effective hours available = H1 + off + mob
    gain = max(0.0, H0 * (1 - a_share) / (H1 + off + mob) - 1)
    return {"region": region, "case": case_name, "theta_market": theta["theta_market"],
            "theta_care": theta["theta_care"], "mobilisation_variant": case["mobilisation"],
            "takeup_T1": r1, "takeup_T2": r2, "takeup_T3": r3, "mobilised_persons_ths": persons, "entrant_productivity": case["rho"],
            "avoidable_level": case["avoidable"], "hours_before_ths": H0, "hours_gap_ths": gap,
            "covered_by_theta_ths": off, "covered_by_mobilisation_ths": mob,
            "covered_by_avoidable_output_ths": avoid,
            "share_gap_theta": off / gap, "share_gap_mobilisation": mob / gap, "share_gap_avoidable": avoid / gap,
            "uncovered_hours_ths": max(0.0, gap - off - mob - avoid),
            "uncovered_share_of_all_hours": max(0.0, gap - off - mob - avoid) / H0,
            "residual_required_productivity_gain": gain,
            "gap_fully_covered": covered >= gap - 1e-6}


def load_inputs():
    v62 = UNIRA / "v62"
    sectors = [r for r in read_csv(v62 / "outputs" / "labour_sector_year.csv")
               if r["year"] == "2023" and r["scenario"] == "cap30_employees_constant_absence"
               and r["nace_r2"] != "TOTAL_bottom_up"]
    return {"v62cfg": json.loads((v62 / "config" / "v62_config.json").read_text()), "sectors": sectors,
            "reserve": read_csv(v62 / "outputs" / "labour_reserve_country_year.csv"),
            "flows": read_csv(ROOT.parent / "flows" / "outputs" / "takeup_rates.csv"),
            "io": json.loads((ROOT.parent / "io" / "outputs" / "summary.json").read_text()),
            "health": read_csv(ROOT.parent / "health" / "outputs" / "health_staffing.csv")}


def main():
    inputs = load_inputs()
    rows = [ledger(reg, name, case, inputs) for reg in ("FR", "EU27_2020") for name, case in CASES.items()]
    (ROOT / "outputs").mkdir(exist_ok=True)
    with (ROOT / "outputs" / "year1_ledger.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows({k: round(v, 6) if isinstance(v, float) else v for k, v in r.items()} for r in rows)
    health = [{k: r[k] for k in ("occupation", "practising", "extra_needed_year1", "lead_time_years",
                                 "years_to_close_if_intake_plus_100pct") if k in r} for r in inputs["health"]]
    (ROOT / "outputs" / "summary.json").write_text(json.dumps({"ledger": rows, "health_year1": health}, indent=2))
    for r in rows:
        print(f"{r['region']:10s} {r['case']:10s} gap={r['hours_gap_ths']/1e6:5.2f}bn  theta={r['share_gap_theta']*100:4.0f}%  "
              f"mobil={r['share_gap_mobilisation']*100:4.0f}%  avoid={r['share_gap_avoidable']*100:4.0f}%  "
              f"uncovered={r['uncovered_share_of_all_hours']*100:5.1f}% of hours  gain={r['residual_required_productivity_gain']*100:5.1f}%")
    for h in health:
        print(h)


if __name__ == "__main__":
    main()
